/** Plain-language words for chords and terms — for people without music lessons. */
import { SHARP_NAMES, prefersFlats } from './notes'

/** Russian plural form: 1 такт, 2 такта, 5 тактов. */
export function plural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(Math.trunc(n)) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b === 1) return one
  if (b >= 2 && b <= 4) return few
  return many
}

/** Should the notes of this chord be spelt with flats (Ab: C-Eb-Ab) rather than sharps? */
export function chordFlats(name: string): boolean {
  const m = /^([A-G])([#b]?)(.*?)(?:\/.*)?$/.exec(name.trim())
  if (!m) return false
  if (m[2]) return m[2] === 'b'
  const minor = /^(m(?!aj)|dim)/.test(m[3])
  return prefersFlats(SHARP_NAMES.indexOf(m[1]), minor ? 'minor' : 'major')
}

