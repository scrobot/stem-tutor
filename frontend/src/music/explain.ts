/** "Am" → минор, грустный; "F/C" → мажор, нижняя нота C. Null for names it does not know. */
export function chordInfo(name: string): { short: string; mood: string } | null {
  const m = /^([A-G](?:#|b)?)(.*?)(?:\/([A-G](?:#|b)?))?$/.exec(name.trim())
  if (!m) return null
  const q = QUALITY[m[2]]
  if (!q) return null
  return { short: m[3] ? `${q.short}, внизу ${m[3]}` : q.short, mood: q.mood }
}

